// PostgreSQL runs on a worker so the existing synchronous domain transactions
// retain their boundaries while using one dedicated database connection.
import { parentPort, workerData } from 'node:worker_threads';
import pg from 'pg';
const { Client, types } = pg;
types.setTypeParser(20, value => { const n=Number(value); if(!Number.isSafeInteger(n)) throw new Error('PostgreSQL integer exceeds the safe JavaScript range'); return n; });
types.setTypeParser(1700, value => {const n=Number(value);if(!Number.isSafeInteger(n))throw new Error('PostgreSQL numeric exceeds the safe integer range');return n;});
const client = new Client({ connectionString: workerData.url, connectionTimeoutMillis: 15000, query_timeout: 30000 });
let connected=false;
const identityTables = new Set(['users','items','orders','lines','payments','expenses','products','inventory_movements','audit_log','recipes']);
function convert(sql) {
 let text=sql.replace(/\b(id) INTEGER PRIMARY KEY\b/g, '$1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(/\bINTEGER\b/g,'BIGINT');
 text=text.replace(/\bINSERT OR IGNORE INTO\b/i,'INSERT INTO');
 if (/\bINSERT OR IGNORE INTO\b/i.test(sql)) text=text.trim().replace(/;?$/, ' ON CONFLICT DO NOTHING');
 let i=0, quoted=false, result='';
 for(let p=0;p<text.length;p++) {const c=text[p]; if(c==="'" && quoted && text[p+1]==="'"){result+="''";p++;continue;} if(c==="'")quoted=!quoted; result+=c==='?'&&!quoted?`$${++i}`:c;}
 return result;
}
async function execute({method,sql,args=[]}) {
 if(method==='init') { await client.connect(); connected=true; await client.query('SELECT pg_advisory_lock(70533861)'); return null; }
 if(method==='ready') {await client.query('SELECT pg_advisory_unlock(70533861)');return null;}
 if(method==='close') {await client.end();connected=false;return null;}
 if(!connected) throw new Error('PostgreSQL is not connected');
 if(sql==='BEGIN IMMEDIATE') {await client.query('BEGIN');await client.query('SELECT pg_advisory_xact_lock(70533861)');return null;}
 if(sql.startsWith('PRAGMA table_info(')) {const table=sql.match(/^PRAGMA table_info\(([a-z_]+)\)$/i)?.[1];if(!table)throw new Error('Invalid table name'); const r=await client.query('SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=$1',[table]);return r.rows;}
 if(sql.includes('PRAGMA foreign_keys=ON')) sql=sql.replace(/PRAGMA foreign_keys=ON; PRAGMA journal_mode=WAL; PRAGMA busy_timeout=5000;/,'');
 let query=convert(sql);
 const insert=sql.match(/^\s*INSERT\s+INTO\s+([a-z_]+)/i);
 if(method==='run' && insert && identityTables.has(insert[1].toLowerCase())) query=query.replace(/;?\s*$/,' RETURNING id');
 const result=await client.query(query,args);
 if(method==='exec') return null;
 if(method==='all') return result.rows;
 if(method==='get') return result.rows[0] ?? null;
 if(method==='run') return {changes:result.rowCount,lastInsertRowid:result.rows?.[0]?.id??0};
 throw new Error('Unknown database operation');
}
parentPort.on('message',async msg=>{
 const signal=new Int32Array(msg.buffer,0,2), out=new Uint8Array(msg.buffer,8);
 try {const value=await execute(msg);const bytes=new TextEncoder().encode(JSON.stringify({value}));if(bytes.length>out.length)throw new Error('Database response exceeds the supported size');out.set(bytes);Atomics.store(signal,1,bytes.length);}
 catch(error){const bytes=new TextEncoder().encode(JSON.stringify({error:error.message,code:error.code}));out.set(bytes);Atomics.store(signal,1,bytes.length);}
 Atomics.store(signal,0,1);Atomics.notify(signal,0);
});
